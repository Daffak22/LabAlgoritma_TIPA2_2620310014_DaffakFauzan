#include <iostream>
#include <string>

using namespace std;

int main() {
    
    float isiFloat = 1.23;
    double isiDouble = 1.23213;
    int isiInt = 1;
    char isiChar = 'A';
    string isiString = "Daffak fauzan";

    cout << "Float : " << isiFloat << endl;
    cout << "Double : " << isiDouble << endl;
    cout << "Int : " << isiInt << endl;
    cout << "Char : " << isiChar << endl;
    cout << "String : " << isiString << endl;

    return 0; // Opsional, tapi disarankan
}